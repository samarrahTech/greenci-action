// Playwright config handling with no dependency on a CI toolkit: only fs and
// path. The GitHub action (src/test-runner.ts) and the Azure DevOps task
// (azure-devops/index.ts) both use it, each with its own logging.
import * as fs from 'fs';
import * as path from 'path';

/** Single-quoted TS string literal: inputs come from action inputs and package.json. */
export function q(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r?\n/g, '\\n')}'`;
}

// Every name Playwright itself looks for, in its order.
export const PLAYWRIGHT_CONFIG_FILES = [
  'playwright.config.ts',
  'playwright.config.js',
  'playwright.config.mts',
  'playwright.config.mjs',
  'playwright.config.cts',
  'playwright.config.cjs',
];
export const GENERATED_CONFIG_MARKER = '// Generated by GreenCI for this run.';

export function findPlaywrightConfig(workDir: string): string | null {
  return PLAYWRIGHT_CONFIG_FILES.find((f) => fs.existsSync(path.join(workDir, f))) ?? null;
}

/** Run-only files: written next to the repo's config, removed when the run ends, never committed. */
export const BASE_URL_OVERRIDE_CONFIGS = ['playwright.greenci.config.ts', 'playwright.greenci.config.mjs'];

/** An ES-module config gets an ES-module wrapper, so it is imported, never require()d. */
export function overrideConfigName(configFile: string): string {
  return /\.m[jt]s$/.test(configFile) ? BASE_URL_OVERRIDE_CONFIGS[1] : BASE_URL_OVERRIDE_CONFIGS[0];
}

/**
 * Source of the config that puts the `base-url` input in charge. It loads the
 * repo's own config and changes only what points at the app:
 *
 * - `use.baseURL` becomes the input.
 * - A project's own `baseURL` becomes the input when it named the same app as
 *   the top level (or when the config only ever names one URL). A project
 *   pointed somewhere else (an admin app, an API) keeps its URL.
 * - `webServer` is dropped when the input is not a local address: the app is
 *   already deployed, and Playwright would otherwise start or wait for a
 *   local server nobody will test.
 *
 * Everything else (projects, timeouts, reporters) stays as the repo wrote it.
 * The URL is read from BASE_URL, which runPlaywrightFile sets, so no input is
 * spliced into source. Plain JavaScript on purpose: the same text is valid as
 * .ts and as .mjs.
 */
export function baseUrlOverrideSource(configFile: string): string {
  // A .ts config is imported without the extension; every other kind needs it.
  const specifier = `./${configFile.endsWith('.config.ts') ? configFile.slice(0, -3) : configFile}`;
  return `// Written by GreenCI for this run: this repo's Playwright config with baseURL
// replaced by the action's base-url input. Removed when the run ends.
import userConfig from ${q(specifier)};

const config = userConfig && userConfig.default ? userConfig.default : userConfig;
const baseURL = process.env.BASE_URL;

const own = config.use ? config.use.baseURL : undefined;
const projects = config.projects || [];
const named = new Set(projects.map((p) => (p.use ? p.use.baseURL : undefined)).filter(Boolean));
if (own) named.add(own);
const replaces = (url) => !!url && (named.size === 1 || url === own);

let local = false;
try {
  local = ['localhost', '127.0.0.1', '[::1]', '0.0.0.0'].includes(new URL(baseURL).hostname);
} catch {
  local = false;
}

export default {
  ...config,
  use: { ...(config.use || {}), baseURL },
  projects: config.projects
    ? projects.map((p) => (p.use && replaces(p.use.baseURL) ? { ...p, use: { ...p.use, baseURL } } : p))
    : undefined,
  webServer: local ? config.webServer : undefined,
};
`;
}

/**
 * Write the override config next to `configFile` and return its name for
 * `--config`, or null when that config is the one GreenCI generated (it
 * already uses the input). Rewritten on every call, so a leftover from an
 * earlier run can never be the one Playwright loads. Throws if the files
 * cannot be read or written; the caller decides how to report that.
 */
export function writeBaseUrlOverride(workDir: string, configFile: string): string | null {
  if (fs.readFileSync(path.join(workDir, configFile), 'utf-8').includes(GENERATED_CONFIG_MARKER)) return null;
  const name = overrideConfigName(configFile);
  fs.writeFileSync(path.join(workDir, name), baseUrlOverrideSource(configFile), 'utf-8');
  return name;
}

/** Remove the run-only override config so later workflow steps see a clean checkout. */
export function removeBaseUrlOverride(workDir: string): void {
  for (const name of BASE_URL_OVERRIDE_CONFIGS) {
    try {
      fs.unlinkSync(path.join(workDir, name));
    } catch {
      // Not written this run, or already gone.
    }
  }
}

/**
 * Playwright treats a file argument as a regular expression matched against
 * each spec's absolute path. A bare `add.spec.ts` therefore also ran
 * `expenses-add.spec.ts`, any `add.spec.ts` in another folder, and anything
 * the unescaped dots happened to match, and their failures were reported
 * against this spec. Match this one file: its path from the repo root,
 * escaped, anchored at the end.
 */
export function specFilter(workDir: string, filePath: string): string {
  return fileFilter(path.relative(workDir, filePath).split(path.sep).join('/'));
}

/**
 * Filter for a file by the end of its path: `e2e/add.spec.ts`, or a bare
 * `auth.setup.ts` wherever the repo keeps it. The leading slash is what stops
 * `auth.setup.ts` from also running `oauth.setup.ts`.
 */
export function fileFilter(pathSuffix: string): string {
  return `/${pathSuffix.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`;
}
